#!/usr/bin/env python3
"""Package selected Musyng Kite notes. Source data is parsed, never executed."""
import base64, concurrent.futures, hashlib, json, re, subprocess
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'assets/audio/soundfonts/musyng-kite'
CACHE=Path('/tmp/hjm-soundfonts');CACHE.mkdir(exist_ok=True)
# Every four semitones: at most two semitones of pitch shifting in the covered range.
RANGES={'violin':(52,96),'viola':(44,88),'cello':(32,76),'contrabass':(24,64),'flute':(56,96),'recorder':(56,96),'oboe':(52,92),'alto-saxophone':(44,84)}
NAMES={'alto-saxophone':'alto_sax'}
BASE='https://raw.githubusercontent.com/gleitz/midi-js-soundfonts/gh-pages/MusyngKite/'
def build(item):
 instrument,(lo,hi)=item;name=NAMES.get(instrument,instrument);url=BASE+name+'-mp3.js';cache=CACHE/(name+'-mp3.js')
 if not cache.exists():
  subprocess.run(['curl','--fail','--silent','--show-error','--location','--retry','2','--max-time','90',url,'-o',str(cache)],check=True)
 raw=cache.read_bytes();pairs=dict(re.findall(r'"([A-G][#b]?-?\d+)"\s*:\s*"data:audio/mp3;base64,([A-Za-z0-9+/=]+)"',raw.decode()))
 if not pairs:raise ValueError('Unexpected sample format: '+name)
 def midi_key(note):
  m=re.fullmatch(r'([A-G])([#b]?)(-?\d+)',note)
  return (int(m[3])+1)*12+{'C':0,'D':2,'E':4,'F':5,'G':7,'A':9,'B':11}[m[1]]+({'#':1,'b':-1}.get(m[2],0))
 by_midi={midi_key(note):value for note,value in pairs.items()}
 samples={str(midi):by_midi[midi] for midi in range(lo,hi+1,4)}
 text='// Musyng Kite / Cose; CC BY-SA 3.0. See LICENSE.html.\nScoreSampleBank.register('+json.dumps(instrument)+','+json.dumps(samples,separators=(',',':'))+');\n'
 path=OUT/(instrument+'.js');path.write_text(text)
 return instrument,{'path':str(path.relative_to(ROOT)),'version':hashlib.sha256(text.encode()).hexdigest()[:12],'notes':list(map(int,samples)),'bytes':len(text),'source':url,'sourceSha256':hashlib.sha256(raw).hexdigest()}
OUT.mkdir(parents=True,exist_ok=True)
with concurrent.futures.ThreadPoolExecutor(max_workers=3) as pool: manifest=dict(pool.map(build,RANGES.items()))
(ROOT/'js/data/score-samples.js').write_text("'use strict';\n// Generated by scripts/build-score-samples.py.\nconst SCORE_SAMPLE_MANIFEST="+json.dumps(manifest,ensure_ascii=False,separators=(',',':'))+';\n')
(OUT/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Packaged',len(manifest),'instruments,',sum(v['bytes'] for v in manifest.values()),'bytes')
